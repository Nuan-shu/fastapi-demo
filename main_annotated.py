# ─────────────────────────────────────────────────────────────
# 第 1 行：导入 FastAPI 框架
# ─────────────────────────────────────────────────────────────
# FastAPI 是一个 Python 类，它帮你处理所有 HTTP 协议的底层细节。
# 你不需要自己解析 HTTP 请求头、不需要处理 TCP 连接。
from fastapi import FastAPI

# ─────────────────────────────────────────────────────────────
# 第 2 行：导入 Pydantic 的数据校验基类
# ─────────────────────────────────────────────────────────────
# BaseModel 是所有数据模型的"父母类"。
# 你定义一个类继承它，就自动获得了数据校验能力。
# 原理：BaseModel 内部重写了 __init__，在创建实例时检查每个字段。
from pydantic import BaseModel

# ─────────────────────────────────────────────────────────────
# 第 4 行：创建应用实例
# ─────────────────────────────────────────────────────────────
# FastAPI() 创建了一个"应用"对象，命名为 app。
# 之后所有的路由注册、配置都通过这个 app 来完成。
# 可以理解为：app 是你的整个 Web 服务的"总控制器"。
# 参数 title 和 version 可选，会显示在 /docs 页面顶部。
app = FastAPI()


# ─────────────────────────────────────────────────────────────
# 以下是「路由」部分 — 把 URL 路径绑定到 Python 函数
# ─────────────────────────────────────────────────────────────

# ────────────────────────────────────
# 路由 1：GET /  首页
# ────────────────────────────────────
# @app.get("/") 是 Python 装饰器语法。
# 等价于人话：「app，登记一下：当有人用 GET 方法访问 / 路径时，调用下面这个函数。」
#
# 装饰器工作原理（简化版）：
#   @app.get("/")
#   def home(): ...
#   等价于 →
#   home = app.get("/")(home)
#   FastAPI 内部把路径 "/" 和函数 home 存入一张路由表中。
@app.get("/")
def home():
    # return 后面的字典，FastAPI 会自动转成 JSON。
    # JSON 格式：{"message": "Hello, FastAPI!"}
    # 等价代码（你不需要写）：json.dumps({"message": "Hello, FastAPI!"})
    # FastAPI 还自动设置了 Content-Type: application/json
    return {"message": "Hello, FastAPI!"}


# ────────────────────────────────────
# 路由 2：GET /health  健康检查
# ────────────────────────────────────
# 同样的模式：装饰器声明路径和方法，函数写业务逻辑。
# 函数名叫 health_check，但这个名称不重要——
# 决定「什么时候调这个函数」的是上面那行 @app.get("/health")，不是函数名。
@app.get("/health")
def health_check():
    return {"status": "running"}


# ─────────────────────────────────────────────────────────────
# 以下是「数据模型」部分 — 定义请求体的格式
# ─────────────────────────────────────────────────────────────

# ────────────────────────────────────
# Question 数据模型
# ────────────────────────────────────
# class Question(BaseModel):
#   class：定义一个类（数据模板）
#   Question：类名，可以随便取
#   (BaseModel)：继承 Pydantic 的 BaseModel → 获得自动校验能力
#
# 字段声明语法：
#   字段名: 类型 = 默认值（可选）
#   字段名: 类型           （必填，不写 =）
class Question(BaseModel):
    # content 字段：必填，类型必须是 str（字符串）
    # 如果请求里没有 content，FastAPI 返回 422
    # 如果 content 是数字（如 123），FastAPI 也会返回 422
    content: str

    # model 字段：可选，类型是 str，默认值为 "deepseek"
    # 如果请求里没有 model，自动填入 "deepseek"
    # 这意味着下面的调用都是合法的：
    #   {"content": "你好"}              → model = "deepseek"（默认）
    #   {"content": "你好", "model": "gpt4"} → model = "gpt4"（覆盖）
    model: str = "deepseek"


# ─────────────────────────────────────────────────────────────
# 以下是「POST 路由」部分 — 接收数据 + 处理 + 返回
# ─────────────────────────────────────────────────────────────

# ────────────────────────────────────
# 路由 3：POST /ask  提问接口
# ────────────────────────────────────
# @app.post("/ask")：POST 方法，路径 /ask
# 和 GET 的区别：POST 用于「发送数据给服务器」，GET 用于「从服务器拿数据」
@app.post("/ask")
def ask(question: Question):
    #                              ↑
    #         参数类型标注：question 必须是 Question 类型
    #
    # FastAPI 看到这个标注，自动做三件事：
    #   1. 从 HTTP 请求体中读取 JSON
    #   2. 用 Question 模型校验数据（content 在不在？类型对不对？）
    #   3. 校验通过 → 把数据塞进 question 变量
    #      校验失败 → 自动返回 422，不执行函数体

    # question.content  → 用户输入的问题文本
    # question.model    → 用户选的模型名（或默认的 "deepseek"）
    # f"..."            → Python f-string，把变量值拼进字符串
    reply = f"你问了：{question.content}（模型：{question.model}）"

    # return 的字典自动变 JSON，自动设 Content-Type: application/json
    # 这个字典里有两个 key：
    #   "answer" → 拼好的回答文本
    #   "model"  → 用了哪个模型
    return {"answer": reply, "model": question.model}
